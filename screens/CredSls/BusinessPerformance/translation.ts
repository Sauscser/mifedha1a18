const languages = Object.keys(values) as Locale[];
if (languages.some(language => values[language].length !== keys.length)) {
  throw new Error('Business performance translations have inconsistent entry counts.');
}

const translations = Object.fromEntries(
  languages.map(language => [
    language,
    {
      ...Object.fromEntries(keys.map((key, index) => [key, values[language][index]])),
      daily: periodValues[language][0],
      weekly: periodValues[language][1],
      monthly: periodValues[language][2],
      ...geographyValues[language],
      ...operationalValues[language],
    },
  ])
) as Record<Locale, Record<Key, string>>;

export const useBusinessPerformanceTranslation = () => {
  const { i18n } = useTranslation();
  const language = (i18n.language?.split('-')[0] || 'en') as Locale;
  const dictionary = translations[language] || translations.en;
  return useMemo(
    () => (key: Key, params: Record<string, string | number> = {}) =>
      dictionary[key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? '')),
    [dictionary]
  );
};
